/* Create a procedure to update the salary of an employee using the
employee ID. Handle the exception if the employee ID does not exist. */

CREATE OR REPLACE PROCEDURE UPDATE_SAL(ENO IN EMP.EID%TYPE,UPDATESAL NUMBER)
IS

BEGIN
	UPDATE EMP SET BASICSAL = UPDATESAL WHERE EID = ENO;
	
	IF SQL%ROWCOUNT = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;
	
	DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID IS:'||ENO);
	DBMS_OUTPUT.PUT_LINE('SALARY UPDATED SUCCESSFULLY.');
	
EXCEPTION
	WHEN NO_DATA_FOUND THEN 
		DBMS_OUTPUT.PUT_LINE('INVALID NUMBER PLEASE ENTER VALID NUMBER.');
		
END;
/

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	ENO EMP.EID%TYPE := &EMPNO;
	UPDATESAL NUMBER := &SALARY;

BEGIN
	UPDATE_SAL(ENO,UPDATESAL);
			
END;

/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;