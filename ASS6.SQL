/* Create a procedure that accepts Department Number and displays:
 Total Employees
 Average Salary
 Maximum Salary
Use OUT parameters. */

CREATE OR REPLACE PROCEDURE DEPT_INFO(DNO IN EMP.DEPTNO%TYPE,V_TOTAL OUT NUMBER,V_AGE OUT NUMBER,V_MAX OUT NUMBER)
IS

BEGIN
	SELECT COUNT(*),AVG(BASICSAL),MAX(BASICSAL) INTO V_TOTAL,V_AGE,V_MAX FROM EMP WHERE DEPTNO = DNO;
		
END;
/

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	DNO EMP.DEPTNO%TYPE := &DEPTNO;
	V_TOTAL NUMBER;
	V_AVG NUMBER;
	V_MAX NUMBER;

BEGIN
	DEPT_INFO(DNO,V_TOTAL,V_AVG,V_MAX);
	
	IF V_TOTAL = 0 THEN
        DBMS_OUTPUT.PUT_LINE('INVALID DEPARTMENT NUMBER.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('DEPARTMENT NUMBER IS: '|| DNO);
        DBMS_OUTPUT.PUT_LINE('TOTAL EMPLOYEE IS: '|| V_TOTAL);
        DBMS_OUTPUT.PUT_LINE('AVERAGE SALARY IS: '|| ROUND(V_AVG, 2));
        DBMS_OUTPUT.PUT_LINE('MAXIMUM SALARY IS: '|| V_MAX);
    END IF;
	
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;