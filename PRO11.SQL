/* 11.Write a simple procedure that increases by the salary of employees for
the given department no. by percentage inputted by the user using IN
parameter. Also, handle the exception if inputted department number
not found. */

CREATE OR REPLACE PROCEDURE SAL(V_DEPTNO IN EMP.DEPTNO%TYPE,PER IN NUMBER)
IS
      DEPTNM EMP.DEPTNAME%TYPE;
BEGIN
	SELECT DEPTNAME INTO DEPTNM FROM EMP WHERE DEPTNO = V_DEPTNO;
	UPDATE EMP SET BASICSAL = BASICSAL + BASICSAL*(PER/100) WHERE DEPTNO = V_DEPTNO;
	
	DBMS_OUTPUT.PUT_LINE('---------------------------------');
	DBMS_OUTPUT.PUT_LINE('RECORD UPDATED SUCCESSFULLY.');
	DBMS_OUTPUT.PUT_LINE('DEPARTMENT NAME IS:'||DEPTNM);
	DBMS_OUTPUT.PUT_LINE('DEPARTMENT NO:'||V_DEPTNO);
	DBMS_OUTPUT.PUT_LINE('PERCENTAGE IS:'||PER);
	
EXCEPTION
	WHEN NO_DATA_FOUND THEN 
		DBMS_OUTPUT.PUT_LINE('INVALID NUMBER PLEASE ENTER VALID NUMBER.');
END;
/	

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	V_DEPTNO EMP.DEPTNO%TYPE := &DEPTNO;
	PER NUMBER := &PER;

BEGIN
	SAL(V_DEPTNO,PER);
	
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;