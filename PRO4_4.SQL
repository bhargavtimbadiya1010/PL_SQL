--WRITE A PROGRAM THAT PRINTS VALUE 1 TO 100 NUMBERS USING WHILE LOOP.

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	I NUMBER(5):=1;

BEGIN	
	DBMS_OUTPUT.PUT_LINE('1 TO 100 USING WHILE LOOP');
	WHILE I <= 100
	LOOP
		DBMS_OUTPUT.PUT(RPAD(I,5));
		IF MOD(I,10) = 0 THEN
			DBMS_OUTPUT.NEW_LINE;
		END IF;
		I:=I+1; 
		--EXIT WHEN I>100;
	END LOOP;
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;