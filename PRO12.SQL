/* Write a procedure that search whether the given employee number is
present or not in the table if present then print name, salary and
department number of that employee. (Use both IN and OUT mode
variables) and Write a PL/SQL block to call the SEARCH_EMP procedure. */

CREATE OR REPLACE PROCEDURE SEARCH_EMP(V_EMPNO IN EMP.EID%TYPE,V_NAME OUT EMP.ENAME%TYPE,V_BSAL OUT EMP.BASICSAL%TYPE,V_DEPTNO OUT EMP.DEPTNO%TYPE)
IS
	
BEGIN

	SELECT ENAME,BASICSAL,DEPTNO INTO V_NAME,V_BSAL,V_DEPTNO FROM EMP WHERE EID = V_EMPNO;


END;
/	

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	V_DEPTNO EMP.DEPTNO%TYPE;
	V_EMPNM EMP.ENAME%TYPE ;
	V_BSAL EMP.BASICSAL%TYPE ;
	V_EMPNO EMP.EID%TYPE := &EMPNO;
	
BEGIN
		SEARCH_EMP(V_EMPNO,V_EMPNM,V_BSAL,V_DEPTNO);
		DBMS_OUTPUT.PUT_LINE('EMPLOYEE NAME IS:'||V_EMPNM);
		DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID IS:'||V_EMPNO);
		DBMS_OUTPUT.PUT_LINE('DEPARTMENT NO IS:'||V_DEPTNO);
		DBMS_OUTPUT.PUT_LINE('BASIC SALARY IS:'||V_BSAL);

EXCEPTION
	WHEN NO_DATA_FOUND THEN 
		DBMS_OUTPUT.PUT_LINE('INVALID NUMBER PLEASE ENTER VALID NUMBER.');
	
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;