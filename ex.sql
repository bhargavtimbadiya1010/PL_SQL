/* Write a function that returns the year category of an employee.
Categories:
Ծ 1 - 5 year  fresher  
Ծ 10 year senior 
Ծ 10 < super senior */

CREATE OR REPLACE FUNCTION YEAR_CAT(V_EMPNO IN EMP1.EMPNO%TYPE)
RETURN VARCHAR2
IS
    V_HIREDATE EMP1.HIREDATE%TYPE;
    V_EXP NUMBER;
    
BEGIN

    SELECT HIREDATE INTO V_HIREDATE FROM EMP1 WHERE EMPNO = V_EMPNO;

    V_EXP := FLOOR((SYSDATE - V_HIREDATE) / 365);

    IF V_EXP <= 5 THEN
        RETURN 'FRESHER';

    ELSIF V_EXP <= 10 THEN
        RETURN 'SENIOR';

    ELSE
        RETURN 'SUPER SENIOR';

    END IF;

END;
/

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
    V_EMPNO EMP1.EMPNO%TYPE := &EMPNO;
    V_CAT VARCHAR2(20);
	V_HIREDATE EMP1.HIREDATE%TYPE;
    V_EXP NUMBER;

BEGIN
	SELECT HIREDATE INTO V_HIREDATE FROM EMP1 WHERE EMPNO = V_EMPNO;

	V_EXP := FLOOR((SYSDATE - V_HIREDATE) / 365);
    V_CAT := YEAR_CAT(V_EMPNO);

    DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID: ' || V_EMPNO);
	DBMS_OUTPUT.PUT_LINE('YEAR OF EXPERIENCE: ' || V_EXP);
    DBMS_OUTPUT.PUT_LINE('CATEGORY: ' || V_CAT);

EXCEPTION

    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('INVALID EMPLOYEE NUMBER.');

END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;

