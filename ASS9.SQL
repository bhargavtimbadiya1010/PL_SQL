/* Create a package named PKG_EMPLOYEE containing:
 Function to calculate the annual salary of an employee.
 Procedure to show employee information using the employee ID.
Call each package object separately. */

CREATE OR REPLACE PACKAGE MYPACK AS 
	PROCEDURE EMP_INFO (V_ID IN EMP.EID%TYPE);
	FUNCTION AUL_SAL (V_ID IN EMP.EID%TYPE) RETURN NUMBER;
END MYPACK;
/

CREATE OR REPLACE PACKAGE BODY MYPACK AS

	PROCEDURE EMP_INFO(V_ID IN EMP.EID%TYPE)
	IS
		V_NAME EMP.ENAME%TYPE;
		V_BSAL EMP.BASICSAL%TYPE;
		V_DEPTNO EMP.DEPTNO%TYPE;
		
	BEGIN
		SELECT ENAME,BASICSAL,DEPTNO INTO V_NAME,V_BSAL,V_DEPTNO FROM EMP WHERE EID = V_ID;
		
		DBMS_OUTPUT.PUT_LINE('EMPLOYEE NAME IS:'||V_NAME);
		DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID IS:'||V_ID);
		DBMS_OUTPUT.PUT_LINE('DEPARTMENT NO IS:'||V_DEPTNO);
		DBMS_OUTPUT.PUT_LINE('BASIC SALARY IS:'||V_BSAL);
		
	EXCEPTION
        WHEN NO_DATA_FOUND THEN
            DBMS_OUTPUT.PUT_LINE('INVALID EMPLOYEE NUMBER.');
		
	END EMP_INFO;
	
	FUNCTION AUL_SAL(V_ID IN EMP.EID%TYPE) RETURN NUMBER IS
		V_SAL NUMBER;
		
    BEGIN
		SELECT BASICSAL*12 INTO V_SAL FROM EMP WHERE EID = V_ID;
		RETURN V_SAL;
				
	END AUL_SAL;
	
	
END MYPACK;
/

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	V_ID EMP.EID%TYPE := &EMPNO;
    V_SAL NUMBER;

BEGIN
	MYPACK.EMP_INFO(V_ID);
	
    V_SAL := MYPACK.AUL_SAL(V_ID);
	DBMS_OUTPUT.PUT_LINE('ANNUAL SALARY : '||V_SAL);
  
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;