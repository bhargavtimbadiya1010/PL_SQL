/* Write a PL/SQL block to delete the record of employee for given EID. */

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;


DECLARE
	ID NUMBER := &EID;
	V_ID NUMBER;

BEGIN
    SELECT EID INTO V_ID FROM EMP WHERE EID = ID;
	
	DELETE FROM EMP WHERE EID = ID;
	DBMS_OUTPUT.PUT_LINE('EMPLOYEE RECORD EID '||V_ID||' IS DELETED');
	
EXCEPTION
	WHEN NO_DATA_FOUND THEN
		DBMS_OUTPUT.PUT_LINE('ERROR: '||SQLERRM);
			
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;