/* 19.Write a trigger that restricts the entry of record if salary is greater than
Rs.50000. */

SET SERVEROUTPUT ON;

CREATE OR REPLACE TRIGGER SAL_TRG
BEFORE INSERT ON EMP 
FOR EACH ROW 

BEGIN
  IF :NEW.BASICSAL > 50000 THEN
	RAISE_APPLICATION_ERROR(-20420,'THIS RECORD ID RESTRICTED BECAUSE salary IS GREATER THAN 50000 ');
  END IF;

END;
/

SET SERVEROUTPUT OFF;
