--AREA OF CIRCLE

SET SERVEROUTPUT ON
SET VERIFY OFF
SET FEEDBACK OFF

DECLARE
	PI CONSTANT NUMBER(7,2) := 3.14;
	R NUMBER(5) := &R;
	AREA NUMBER(7,2);
BEGIN
	AREA := PI*POWER(R,2);
	DBMS_OUTPUT.PUT_LINE('AREA OF CIRCLE IS: '||AREA);
END;
/

SET SERVEROUTPUT OFF
SET VERIFY ON
SET FEEDBACK ON