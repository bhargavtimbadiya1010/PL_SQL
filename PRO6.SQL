/* 6.Write a PL/SQL block which accepts measurement in feet and displays it
in cm, inch and meter. */

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	FEET NUMBER := &FEET;
	INCH NUMBER;
	CM NUMBER;
	METER NUMBER;

BEGIN
	INCH := FEET*12;
	CM := FEET*30.48;
	METER := FEET*0.3048;
	
	DBMS_OUTPUT.PUT_LINE('FEET: '||FEET);
	DBMS_OUTPUT.PUT_LINE('INCH: '||INCH);
	DBMS_OUTPUT.PUT_LINE('CM: '||CM);
	DBMS_OUTPUT.PUT_LINE('METER: '||METER);
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;