/* Write a PL/SQL block which converts temperature from Celsius to
Fahrenheit. */

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

ACCEPT C NUMBER PROMPT '1.CELSIUS TO FAHRENHEIT:  2.FAHRENHEIT TO CELSIUS: ';

DECLARE
	CHOISE NUMBER := &C;
	CELSIUS NUMBER := &CELSIUS;
	FAHRENHEIT NUMBER := &FAHRENHEIT;

BEGIN
    IF CHOISE = 1 THEN
		DBMS_OUTPUT.PUT_LINE('CELSIUS: '||CELSIUS);
		FAHRENHEIT := (CELSIUS * 9/5) + 32;
		DBMS_OUTPUT.PUT_LINE('FAHRENHEIT: '||ROUND(FAHRENHEIT,2));
		
	ELSIF CHOISE = 2 THEN
		DBMS_OUTPUT.PUT_LINE('FAHRENHEIT: '||FAHRENHEIT);
		CELSIUS := (FAHRENHEIT - 32) * 5/9;
		DBMS_OUTPUT.PUT_LINE('CELSIUS: '||ROUND(CELSIUS,2));
		
	ELSE
		DBMS_OUTPUT.PUT_LINE('INVALID INPUT PLEASE ENTER VALID CHOISE');
		
	END IF;
			
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;