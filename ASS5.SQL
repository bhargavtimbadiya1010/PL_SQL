/* 5.Write a PL/SQL block that accepts three numbers and displays:
 Largest number
 Smallest number
 Average
 Also, check whether all numbers are equal.*/
 
SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
    NUM1 NUMBER := &NUM1;
    NUM2 NUMBER := &NUM2;
    NUM3 NUMBER := &NUM3;

    LARGEST  NUMBER;
    SMALLEST NUMBER;
    AVERAGE  NUMBER;

BEGIN
    LARGEST := GREATEST(NUM1, NUM2, NUM3);
    SMALLEST := LEAST(NUM1, NUM2, NUM3);
    AVERAGE := (NUM1 + NUM2 + NUM3)/3;

    DBMS_OUTPUT.PUT_LINE('===== RESULT =====');
    DBMS_OUTPUT.PUT_LINE('LARGEST NUMBER: ' ||LARGEST);
    DBMS_OUTPUT.PUT_LINE('SMALLEST NUMBER: ' ||SMALLEST);
    DBMS_OUTPUT.PUT_LINE('AVERAGE: ' ||ROUND(AVERAGE,2));

    IF NUM1 = NUM2 AND NUM2 = NUM3 THEN
        DBMS_OUTPUT.PUT_LINE('ALL NUMBERS ARE EQUAL');
    ELSE
        DBMS_OUTPUT.PUT_LINE('ALL NUMBERS ARE NOT EQUAL');
    END IF;

END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;