/* 13.Write a procedure that accept employee ID and remove records from
employee table. Also, create a calling program to call procedure. */

CREATE OR REPLACE PROCEDURE DEL_EMP(V_ID IN EMP.EID%TYPE,V_NAME OUT EMP.ENAME%TYPE)
IS
	
BEGIN

	SELECT ENAME INTO V_NAME FROM EMP WHERE EID = V_ID;
	DELETE FROM EMP WHERE EID = V_ID;

END;
/	

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	V_ID EMP.EID%TYPE := &EMPNO;
	V_NAME EMP.ENAME%TYPE;
	
BEGIN
		DEL_EMP(V_ID,V_NAME);
		DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID IS: '||V_ID||' SUCCESSFULLY DELETED');
				
EXCEPTION
	WHEN NO_DATA_FOUND THEN 
		DBMS_OUTPUT.PUT_LINE('INVALID NUMBER PLEASE ENTER VALID NUMBER.');
	
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;