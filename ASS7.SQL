/* Create a function that returns the annual salary of an employee
(salary × 12). Call the function inside a SELECT statement. */


CREATE OR REPLACE FUNCTION AUL_SAL(V_ID IN EMP.EID%TYPE)
RETURN NUMBER
IS	
	V_NAME EMP.ENAME%TYPE;
	V_SAL NUMBER;
	
BEGIN
	SELECT BASICSAL*12 INTO V_SAL FROM EMP WHERE EID = V_ID;
	RETURN V_SAL;
				
END;
/	

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
    V_ID EMP.EID%TYPE;
    V_NAME EMP.ENAME%TYPE;
    V_SAL NUMBER;
	
BEGIN

    SELECT EID,ENAME,AUL_SAL(EID) INTO V_ID,V_NAME,V_SAL FROM EMP WHERE EID = &EMPNO;

    DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID: '||V_ID);
    DBMS_OUTPUT.PUT_LINE('EMPLOYEE NAME: '||V_NAME);
    DBMS_OUTPUT.PUT_LINE('ANNUAL SALARY: '||V_SAL);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('INVALID EMPLOYEE NUMBER.');

END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;