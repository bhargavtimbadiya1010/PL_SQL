--AREA OF CIRCLE
--AREA OF RECTANGLE
--AREA OF CIRCUMFERENCE CIRCLE

SET SERVEROUTPUT ON
SET VERIFY OFF
SET FEEDBACK OFF

DECLARE
	PI CONSTANT NUMBER(7,2) := 3.14;
	R NUMBER(5) := &R;
	L NUMBER(20) := &L;
	W NUMBER(20) := &W;
BEGIN
	DBMS_OUTPUT.PUT_LINE('AREA OF CIRCLE:');
	DBMS_OUTPUT.PUT_LINE(' ');
	DBMS_OUTPUT.PUT_LINE('AREA OF CIRCLE IS: '||PI*POWER(R,2));
	
	DBMS_OUTPUT.PUT_LINE('======================================');
	
	DBMS_OUTPUT.PUT_LINE('AREA OF RECTANGLE:');
	DBMS_OUTPUT.PUT_LINE('  ');
	DBMS_OUTPUT.PUT_LINE('AREA OF RECTANGLE IS: '||L*W);
	
	DBMS_OUTPUT.PUT_LINE('======================================');
	
	DBMS_OUTPUT.PUT_LINE('AREA OF  CIRCUMFERENCE CIRCLE:');
	DBMS_OUTPUT.PUT_LINE('  ');
	DBMS_OUTPUT.PUT_LINE('AREA OF CIRCUMFERENCE CIRCLE IS: '||2*PI*R);
END;
/

SET SERVEROUTPUT OFF
SET VERIFY ON
SET FEEDBACK ON