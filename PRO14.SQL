/* Write a function that returns the age category of an employee.
Categories:
Ծ AGE < 18 MINOR
Ծ 18-60 ADULT
Ծ 60 SENIOR */

CREATE OR REPLACE FUNCTION AGE_CAT(V_ID IN EMP.EID%TYPE)
RETURN VARCHAR2
IS	
	V_AGE EMP.AGE%TYPE;
	V_CAT VARCHAR2(10);
	
BEGIN
	SELECT AGE INTO V_AGE FROM EMP WHERE EID = V_ID;
	
	IF V_AGE < 18 THEN
		RETURN 'MINOR';
	ELSIF V_AGE <= 60 THEN
		RETURN 'ADULT';
	ELSE
		RETURN 'SENIOR';
	END IF;
END;
/	

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
	V_ID EMP.EID%TYPE := &EMPNO;
	V_CAT VARCHAR2(10);
	V_AGE EMP.AGE%TYPE;
	
BEGIN
	SELECT AGE INTO V_AGE FROM EMP WHERE EID = V_ID;
	
		V_CAT := AGE_CAT(V_ID);
		DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID IS: '||V_ID);
		DBMS_OUTPUT.PUT_LINE('AGE IS: '||V_AGE);
		DBMS_OUTPUT.PUT_LINE('CATEGORY IS: '||V_CAT);
				
EXCEPTION
	WHEN NO_DATA_FOUND THEN 
		DBMS_OUTPUT.PUT_LINE('INVALID NUMBER PLEASE ENTER VALID NUMBER.');
	
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;