/* 15.Write a PACKAGE which includes Package Declaration, Package
Body and call the individual object from the Package. */

CREATE OR REPLACE PACKAGE PACK AS 
	PROCEDURE TOTAL_EMP_BYDEPT;
	FUNCTION TOTAL_MALE_EMP RETURN NUMBER;
END PACK;
/

CREATE OR REPLACE PACKAGE BODY PACK AS

	PROCEDURE TOTAL_EMP_BYDEPT IS
	V_HR NUMBER;
	V_IT NUMBER;
	
	BEGIN
		SELECT COUNT (*) INTO V_HR FROM EMP WHERE DEPTNAME = 'HR';
		SELECT COUNT (*) INTO V_IT FROM EMP WHERE DEPTNAME = 'IT';
		DBMS_OUTPUT.PUT_LINE('TOTAL EMPLOYEE IN HR DEPARTMENT IS: '||V_HR);
		DBMS_OUTPUT.PUT_LINE('TOTAL EMPLOYEE IN IT DEPARTMENT IS: '||V_IT);
		
	END TOTAL_EMP_BYDEPT;
	
	FUNCTION TOTAL_MALE_EMP RETURN NUMBER IS
        VAL_M NUMBER;
    BEGIN
        SELECT COUNT(*) INTO VAL_M FROM EMP WHERE GENDER = 'Male'; 
        RETURN VAL_M;
    END TOTAL_MALE_EMP;
	
END PACK;
/


SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

BEGIN 
	PACK.TOTAL_EMP_BYDEPT();
	DBMS_OUTPUT.PUT_LINE('TOTAL MALE EMPLOYEES: ' || PACK.TOTAL_MALE_EMP());					
END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON; 