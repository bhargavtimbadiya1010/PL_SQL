/* Write a trigger to insert,update and delete the values into the NEWEMP table when the
records are inserted,updated and deleted into the EMP table. */

CREATE OR REPLACE TRIGGER ALL_TRG
BEFORE INSERT OR UPDATE OR DELETE ON EMP 
FOR EACH ROW 

BEGIN
	IF INSERTING THEN
		INSERT INTO NEWEMP VALUES (:NEW.EID,:NEW.ENAME,:NEW.DEPTNO,:NEW.DEPTNAME,:NEW.GENDER,:NEW.AGE,:NEW.BASICSAL);
	ELSIF UPDATING THEN
		INSERT INTO NEWEMP VALUES (:OLD.EID,:OLD.ENAME,:OLD.DEPTNO,:OLD.DEPTNAME,:OLD.GENDER,:OLD.AGE,:OLD.BASICSAL);
	ELSE
		INSERT INTO NEWEMP VALUES (:OLD.EID,:OLD.ENAME,:OLD.DEPTNO,:OLD.DEPTNAME,:OLD.GENDER,:OLD.AGE,:OLD.BASICSAL);
	END IF;
	
END;
