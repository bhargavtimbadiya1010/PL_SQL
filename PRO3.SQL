/* Write a PL/SQL block to calculate the total, percentage and grade of
student based on his/her Rollno from RESULT table. (Create RESULT
table with Rollno, Name, Sub1, Sub2, Sub3, Sub4, Sub5, Total, Per,
Grade attributes with appropriate data type). */

SET SERVEROUTPUT ON;
SET VERIFY OFF;
SET FEEDBACK OFF;

DECLARE
    V_ROLLNO NUMBER(4) := &ROLLNO;
    V_NAME VARCHAR2(20);
    V_S1 NUMBER(5);
    V_S2 NUMBER(5);
    V_S3 NUMBER(5);
    V_S4 NUMBER(5);
    V_S5 NUMBER(5);
    V_TOTAL NUMBER(5);
    V_PER NUMBER(5,2);
    V_GRADE VARCHAR2(20);

BEGIN

    SELECT NAME, SUB1, SUB2, SUB3, SUB4, SUB5 INTO V_NAME, V_S1, V_S2, V_S3, V_S4, V_S5 FROM RESULT WHERE ROLLNO = V_ROLLNO;

    V_TOTAL := V_S1 + V_S2 + V_S3 + V_S4 + V_S5;

    V_PER := V_TOTAL / 5;
	
	IF V_PER < 35 THEN

        DBMS_OUTPUT.PUT_LINE('STATUS: FAIL');

    ELSE

    
		IF (V_PER>=70) THEN
			V_GRADE:='DISTINCTION';
		ELSIF (V_PER>=60 AND V_PER<70) THEN
			V_GRADE:='FIRST CLASS';
		ELSIF (V_PER>=50 AND V_PER<60) THEN
			V_GRADE:='SECOND CLASS';
		ELSE
			V_GRADE:='PASS CLASS';
			
		END IF;

		DBMS_OUTPUT.PUT_LINE('ROLL NO: ' || V_ROLLNO);
		DBMS_OUTPUT.PUT_LINE('NAME: ' || V_NAME);
		DBMS_OUTPUT.PUT_LINE('TOTAL: ' || V_TOTAL);
		DBMS_OUTPUT.PUT_LINE('PERCENTAGE: ' || V_PER);
		DBMS_OUTPUT.PUT_LINE('GRADE: ' || V_GRADE);

		UPDATE RESULT SET TOTAL = V_TOTAL,PER = V_PER,GRADE = V_GRADE WHERE ROLLNO = V_ROLLNO;
		COMMIT;
	END IF;
	
EXCEPTION
	WHEN NO_DATA_FOUND THEN
		DBMS_OUTPUT.PUT_LINE('INVALID CHOISE PLEASE ENTER VALID ROLLNO');

END;
/

SET SERVEROUTPUT OFF;
SET VERIFY ON;
SET FEEDBACK ON;